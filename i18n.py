_current = DEFAULT_LANG


def config_path() -> str:
    """Path to the persisted user config (shares the DiskScope data dir)."""
    base = os.environ.get("LOCALAPPDATA") or os.path.expanduser("~")
    d = os.path.join(base, "DiskScope")
    try:
        os.makedirs(d, exist_ok=True)
    except OSError:
        pass
    return os.path.join(d, "config.json")


def _read_config() -> dict:
    try:
        with open(config_path(), "r", encoding="utf-8") as f:
            data = json.load(f)
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def _write_config(data: dict) -> None:
    path = config_path()
    tmp = path + ".tmp"
    try:
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False)
        os.replace(tmp, path)
    except OSError:
        try:
            os.unlink(tmp)
        except OSError:
            pass


def _normalize(code: str | None) -> str:
    if not code:
        return DEFAULT_LANG
    code = str(code).strip().lower().split("-")[0].split("_")[0]
    return code if code in _CATALOG else DEFAULT_LANG


def set_lang(code: str | None) -> str:
    """Activate a language (no persistence). Returns the effective code."""
    global _current
    _current = _normalize(code)
    return _current


def get_lang() -> str:
    return _current


def load_lang() -> str:
    """Resolve the language for this process.

    Priority: DISKTOP_LANG env var > persisted config > default (English).
    """
    env = os.environ.get("DISKTOP_LANG")
    if env:
        return set_lang(env)
    return set_lang(_read_config().get("lang") or DEFAULT_LANG)



def save_lang(code: str | None = None) -> str:
    """Persist the active (or given) language. Returns the effective code."""
    effective = set_lang(code)
    cfg = _read_config()
    cfg["lang"] = effective
    _write_config(cfg)
    return effective


def age_units(code: str | None = None) -> tuple[str, str, str, str, str]:
    return AGE_UNITS.get(_normalize(code if code is not None else _current),
                         AGE_UNITS[DEFAULT_LANG])


def known(key: str) -> bool:
    """True if ``key`` exists in the reference (English) catalog."""
    return key in _CATALOG[DEFAULT_LANG]


def t(key: str, **kw) -> str:
    """Translate ``key`` in the active language.

    Resolution order: active catalog -> English catalog -> the key itself.
    Formatting errors (missing placeholders) fall back to the raw template.
    """
    src = _CATALOG.get(_current) or _CATALOG[DEFAULT_LANG]
    text = src.get(key)
    if text is None:
        text = _CATALOG[DEFAULT_LANG].get(key, key)
    if kw:
        try:
            return text.format(**kw)
        except (KeyError, IndexError):
            return text
    return text
