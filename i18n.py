"""DiskTop - i18n.py

Internationalization layer.

* Default language is English ("en").
* The language can be changed easily from the Settings menu ([L] Language)
  or on the command line with ``--lang``. The choice is persisted in
  ``%LOCALAPPDATA%\\DiskScope\\config.json`` so it survives restarts.
* Catalogs provided: en (default, complete), fr (complete), es, de.
* ``t(key, **kw)`` resolves in the active catalog, falls back to the English
  catalog, then to the key itself - so a missing translation can never raise.

Design note: only *user-facing* strings are routed through this module. Data
values (paths, sizes, drive names, technical tokens) stay untouched.
"""
